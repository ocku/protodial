#!/usr/bin/env python3
"""Generate compact Unicode grapheme-property tables for protodial.

Usage::

    python scripts/generate_unicode_grapheme_data.py \
      --ucd-dir /path/to/ucd-16.0.0 \
      --output src/protodial/presentation/_grapheme_data.py

The input directory must contain ``auxiliary/GraphemeBreakProperty.txt``,
``emoji/emoji-data.txt``, and ``DerivedCoreProperties.txt`` from the named
Unicode release.  A flat directory containing those three files also works.
"""

from __future__ import annotations

import argparse
import re
from collections.abc import Iterable
from pathlib import Path

UNICODE_VERSION = "16.0.0"

GCB_VALUES = {
    "CR": 1,
    "LF": 2,
    "Control": 3,
    "Extend": 4,
    "ZWJ": 5,
    "Regional_Indicator": 6,
    "Prepend": 7,
    "SpacingMark": 8,
    "L": 9,
    "V": 10,
    "T": 11,
    "LV": 12,
    "LVT": 13,
}
INCB_VALUES = {"Consonant": 1, "Extend": 2, "Linker": 3}


def _source(ucd_dir: Path, nested: str, flat: str) -> Path:
    nested_path = ucd_dir / nested
    return nested_path if nested_path.exists() else ucd_dir / flat


def _check_version(path: Path, marker: str) -> None:
    first_lines = "\n".join(path.read_text(encoding="utf-8").splitlines()[:12])
    if marker not in first_lines:
        raise ValueError(f"{path} is not Unicode {UNICODE_VERSION} data")


def _code_range(text: str) -> tuple[int, int]:
    bounds = text.strip().split("..")
    start = int(bounds[0], 16)
    return start, int(bounds[-1], 16)


def _merge(
    ranges: Iterable[tuple[int, int, int]],
) -> list[tuple[int, int, int]]:
    merged: list[tuple[int, int, int]] = []
    for start, end, value in sorted(ranges):
        if merged and merged[-1][1] + 1 == start and merged[-1][2] == value:
            previous = merged[-1]
            merged[-1] = (previous[0], end, value)
        else:
            merged.append((start, end, value))
    return merged


def _grapheme_break_ranges(path: Path) -> list[tuple[int, int, int]]:
    ranges: list[tuple[int, int, int]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        data = line.split("#", 1)[0]
        if ";" not in data:
            continue
        code_points, property_name = (part.strip() for part in data.split(";"))
        value = GCB_VALUES.get(property_name)
        if value is not None:
            ranges.append((*_code_range(code_points), value))
    return _merge(ranges)


def _binary_ranges(path: Path, property_name: str) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int, int]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        data = line.split("#", 1)[0]
        if ";" not in data:
            continue
        code_points, name = (part.strip() for part in data.split(";"))
        if name == property_name:
            ranges.append((*_code_range(code_points), 1))
    return [(start, end) for start, end, _ in _merge(ranges)]


def _incb_ranges(path: Path) -> list[tuple[int, int, int]]:
    pattern = re.compile(
        r"^\s*([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*InCB\s*;\s*"
        r"(Consonant|Extend|Linker)\b"
    )
    ranges: list[tuple[int, int, int]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = pattern.match(line)
        if match:
            ranges.append(
                (*_code_range(match.group(1)), INCB_VALUES[match.group(2)])
            )
    return _merge(ranges)


def _format(name: str, ranges: Iterable[tuple[int, ...]]) -> str:
    materialized = list(ranges)
    arity = len(materialized[0])
    item_type = ", ".join("int" for _ in range(arity))
    rows = [f"    {item!r}," for item in materialized]
    return (
        f"{name}: tuple[tuple[{item_type}], ...] = (\n"
        + "\n".join(rows)
        + "\n)\n"
    )


def generate(ucd_dir: Path, output: Path) -> None:
    """Generate the Python property-table module from a Unicode data tree."""
    grapheme = _source(
        ucd_dir,
        "auxiliary/GraphemeBreakProperty.txt",
        "GraphemeBreakProperty.txt",
    )
    emoji = _source(ucd_dir, "emoji/emoji-data.txt", "emoji-data.txt")
    derived = ucd_dir / "DerivedCoreProperties.txt"
    _check_version(grapheme, UNICODE_VERSION)
    _check_version(emoji, "Emoji Version 16.0")
    _check_version(derived, UNICODE_VERSION)

    content = f'''\
"""Generated Unicode {UNICODE_VERSION} properties used by UAX #29.

Generated by ``scripts/generate_unicode_grapheme_data.py`` from the Unicode
Character Database. Do not edit by hand.

Source root: https://www.unicode.org/Public/{UNICODE_VERSION}/ucd
Files: auxiliary/GraphemeBreakProperty.txt, emoji/emoji-data.txt, and
DerivedCoreProperties.txt.
"""

from __future__ import annotations

UNICODE_VERSION = "{UNICODE_VERSION}"

GCB_OTHER = 0
GCB_CR = 1
GCB_LF = 2
GCB_CONTROL = 3
GCB_EXTEND = 4
GCB_ZWJ = 5
GCB_REGIONAL_INDICATOR = 6
GCB_PREPEND = 7
GCB_SPACING_MARK = 8
GCB_L = 9
GCB_V = 10
GCB_T = 11
GCB_LV = 12
GCB_LVT = 13

INCB_NONE = 0
INCB_CONSONANT = 1
INCB_EXTEND = 2
INCB_LINKER = 3

'''
    content += _format(
        "GRAPHEME_BREAK_RANGES", _grapheme_break_ranges(grapheme)
    )
    content += "\n"
    content += _format(
        "EXTENDED_PICTOGRAPHIC_RANGES",
        _binary_ranges(emoji, "Extended_Pictographic"),
    )
    content += "\n"
    content += _format("INDIC_CONJUNCT_BREAK_RANGES", _incb_ranges(derived))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")


def main() -> None:
    """Parse command-line arguments and generate the requested module."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--ucd-dir", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()
    generate(arguments.ucd_dir, arguments.output)


if __name__ == "__main__":
    main()
